describe("e2e-pipeline: artifact naming and release directory", () => {
  it("release directory would contain only final installers after purge", () => {
    const shContent = fs.readFileSync(path.join(rootDir, "build.sh"), "utf8");

    // Should purge blockmaps, yml, unpacked
    expect(shContent).toContain("*.blockmap");
    expect(shContent).toContain("*.yml");
    expect(shContent).toContain("*-unpacked");

    // Should NOT purge dmg, exe, AppImage
    expect(shContent).not.toMatch(/rm.*\*\.dmg/);
    expect(shContent).not.toMatch(/rm.*\*\.exe/);
    expect(shContent).not.toMatch(/rm.*\*\.AppImage/);
  });

  it("all primary artifacts have unique names and include arch", () => {
    const artifacts = PRODUCTION_ARTIFACTS.filter((a) => ["x64", "arm64", "ia32"].includes(a.arch) && ["mac", "win", "linux"].includes(a.os));
    const names = artifacts.map((a) => a.file);
    const unique = new Set(names);

    // Within same OS, names must be unique (mac x64 vs arm64 differ)
    const macNames = names.filter((n) => n.endsWith(".dmg"));
    expect(new Set(macNames).size).toBe(macNames.length);

    const winNames = names.filter((n) => n.endsWith(".exe"));
    expect(new Set(winNames).size).toBe(winNames.length);

    const linuxNames = names.filter((n) => n.endsWith(".AppImage"));
    expect(new Set(linuxNames).size).toBe(linuxNames.length);
  });
});
